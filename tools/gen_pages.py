"""Generate the Installation and Release notes pages of every guide.

Sources: apps.json (catalog), data/modules.json (facts from each __manifest__.py) and
data/releases.json (release history taken from git, written for customers).
Run: python3 tools/gen_pages.py   (sync_app.py check runs it too)
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORE = 'https://apps.odoo.com/apps/modules/%s/%s'
ODOO_APPS = {'point_of_sale': 'Point of Sale', 'stock': 'Inventory', 'sale': 'Sales', 'mail': 'Discuss',
             'payment': 'Payment providers (part of Invoicing and Website)', 'base_automation': 'Automation Rules',
             'product': 'Products', 'mrp_workorder': 'Manufacturing work orders (Enterprise)'}
CORE = {'base', 'web', 'base_setup', 'bus'}
NOTE = '# Generated by tools/gen_pages.py from apps.json and data/. Edit those, not this file.'


def load(name):
    with open(os.path.join(ROOT, name), encoding='utf-8') as f:
        return json.load(f)


def series_list(versions):
    parts = [p.strip() for p in versions.split('-')]
    lo, hi = int(float(parts[0])), int(float(parts[-1]))
    return ['%d.0' % v for v in range(lo, hi + 1)]


def needs(mod, mods):
    other = [d for d in mod['depends'] if d in mods]
    odoo = [ODOO_APPS[d] for d in mod['depends'] if d in ODOO_APPS]
    out = []
    if other:
        names = [mods[d]['name'] for d in other]
        out.append(('the ' if any('$' in n for n in names) else 'the free ') + ', '.join(names))
    out += odoo
    return ', '.join(out) if out else 'nothing beyond standard Odoo'


def install_page(app, mods):
    last = series_list(app['versions'])[-1]
    rows = []
    for kind in ('free', 'pro'):
        tech = app.get(kind)
        if not tech:
            continue
        m = mods[tech]
        edition = ('Free' if kind == 'free' else ('Pro, ' + app['price'] if app.get('free') else 'Paid, ' + app['price']))
        rows.append('| %s | `%s` | %s | %s | %s |' % (m['name'], tech, edition, m['license'], needs(m, mods)))
    store = ' and '.join('[%s](%s)' % (mods[app[k]]['name'], STORE % (last, app[k])) for k in ('free', 'pro') if app.get(k))
    extra = []
    if any(mods[app[k]].get('python') for k in ('free', 'pro') if app.get(k)):
        extra.append('- The Python library `requests` must be available on the server. It ships with Odoo, so a standard installation already has it.')
    if app.get('free') and app.get('pro'):
        if app['free'] in mods[app['pro']]['depends']:
            extra.append('- %s is installed on top of %s. Odoo adds %s automatically, and everything you set up in it stays.'
                         % (mods[app['pro']]['name'], mods[app['free']]['name'], mods[app['free']]['name']))
        else:
            extra.append('- %s does not need %s. Install either one, or both.' % (mods[app['pro']]['name'], mods[app['free']]['name']))
    lines = [
        '---', 'title: Installation and compatibility', 'sidebar_label: Installation', 'sidebar_position: 1.5',
        'description: "Supported Odoo versions, required apps and installation steps for %s."' % app['title'], NOTE, '---', '',
        '# Installation and compatibility', '',
        '## Supported versions', '',
        '| Odoo version | %s |' % ' | '.join(series_list(app['versions'])),
        '|---|%s' % ('---|' * len(series_list(app['versions']))),
        '| Supported | %s |' % ' | '.join(['Yes'] * len(series_list(app['versions']))), '',
        "import VersionRequest from '@site/src/components/VersionRequest';", '',
        '<VersionRequest slug="%s" />' % app['slug'], '',
        'Odoo Community and Enterprise, on Odoo.sh or your own server. Odoo Online does not allow third-party apps.', '',
        '## What you install', '',
        '| App | Technical name | Edition | License | Also needs |', '|---|---|---|---|---|', *rows, '',
    ]
    if extra:
        lines += extra + ['']
    lines += [
        '## Install', '',
        '1. Open %s on the Odoo Apps Store and choose your Odoo version.' % store,
        '2. Download the app (paid apps: buy it first, then download it from your Odoo account).',
        '3. Add the folder to your custom apps: on Odoo.sh commit and push it to your repository, on your own server copy it into a folder in your `addons_path` and restart Odoo.',
        '4. In Odoo, turn on developer mode, open **Apps**, click **Update Apps List**, search for **%s** and click **Activate**.' % app['title'], '',
        'The [installation guide](../getting-started/install.md) has more detail for each kind of hosting.', '',
        '## Update to a new version', '',
        '1. Download the new version from the Odoo Apps Store for the same Odoo version.',
        '2. Replace the old app folder with the new one (Odoo.sh: commit and push, your own server: restart Odoo).',
        '3. Open **Apps**, find **%s** and click **Upgrade**.' % app['title'], '',
        'Your settings and data are kept. See the [release notes](./changelog.md) for what changed.', '',
        '## Report a problem', '',
        'See [Support](../support.md) for what to include so we can help quickly.', '',
    ]
    return '\n'.join(lines)


def changelog_page(app, releases):
    lines = ['---', 'title: Release notes', 'sidebar_position: 95',
             'description: "Version history of %s for Odoo."' % app['title'], NOTE, '---', '', '# Release notes', '',
             'The newest release is first. In Odoo the version number starts with the Odoo version, so release 1.1.0 for Odoo 20.0 shows as `20.0.1.1.0`.', '']
    for r in releases:
        lines += ['## %s' % r['version'], '', '*%s, Odoo %s*' % (r['date'], r['series']), '']
        lines += ['- %s' % n for n in r['notes']] + ['']
    return '\n'.join(lines)


def main():
    apps = load('apps.json')['apps']
    mods = load('data/modules.json')
    rel = load('data/releases.json')
    missing = []
    for app in apps:
        d = os.path.join(ROOT, 'docs', app['slug'])
        if not os.path.isdir(d):
            continue
        for k in ('free', 'pro'):
            if app.get(k) and app[k] not in mods:
                missing.append('%s: %s missing from data/modules.json' % (app['slug'], app[k]))
        if app['slug'] not in rel:
            missing.append('%s: no entry in data/releases.json' % app['slug'])
            continue
        with open(os.path.join(d, 'install.md'), 'w', encoding='utf-8') as f:
            f.write(install_page(app, mods))
        with open(os.path.join(d, 'changelog.md'), 'w', encoding='utf-8') as f:
            f.write(changelog_page(app, rel[app['slug']]))
    return missing


if __name__ == '__main__':
    problems = main()
    print('\n'.join(problems) or 'ok')
